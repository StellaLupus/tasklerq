-- Уборка уведомлений в чате (design, решения 3 и 5): `dismissed_at` — когда
-- сообщение уведомления окончательно убрано из чата («🗑 Убрать», замена
-- «😴 Напомню …», замена прежней сводки); NULL — не убрано. Отметку ставят
-- пути, убирающие сообщение; будущие правки отправленных сообщений записи
-- с отметкой не трогают. Автоудаление «✅ Выполнено» отметку не ставит:
-- оно отменяемо. `replaces_message_id` — id сообщения в чате, которое заменит
-- эта (snooze-)доставка после своей отправки; NULL — заменять нечего.
--
-- Миграция аддитивна: существующие строки не переписываются, обе колонки
-- nullable и без значения по умолчанию. Прежние snooze остаются с пустым
-- полем и прежнее сообщение не удаляют; уже отправленные уведомления
-- считаются неубранными.

ALTER TABLE notification_deliveries ADD COLUMN dismissed_at timestamptz;

