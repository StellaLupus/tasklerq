-- Снимок состава утренней сводки (design, решение 1): `digest_items` —
-- упорядоченный список всех строк сводки `{item_id, section, occurrence_key}`
-- (section — `today` / `overdue` / `event`, у события occurrence_key — начало
-- вхождения), записывается при доставке той же транзакцией, в которой
-- ставится сообщение. `digest_hash` — отпечаток последней отрисовки без
-- токенов (design, решение 6). Перерисовка читает состав отсюда, а состояние —
-- из items и событий выполнения.
--
-- Миграция аддитивна: существующие строки не переписываются, обе колонки
-- nullable и без значения по умолчанию. Сводки, доставленные до выката,
-- снимка не имеют (NULL) и шагом sync_digests не обновляются.

ALTER TABLE notification_deliveries
    ADD COLUMN digest_items jsonb,
    ADD COLUMN digest_hash text;