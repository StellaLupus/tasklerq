-- Части исходного текста черновика Telegram: каждое дописанное сообщение
-- отдельной строкой. `raw_text` остаётся склейкой частей через перевод строки,
-- поэтому существующие читатели и ограничение в 2000 символов работают как
-- раньше. Колонка аддитивная: старый код её не видит, старые строки получают
-- пустой массив без бэкфилла.

ALTER TABLE capture_drafts ADD COLUMN raw_parts text[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN capture_drafts.raw_parts IS
    'Исходные сообщения черновика по порядку; raw_text — их склейка через перевод строки';
