-- Аудит выгрузки household: новое значение `audit_event_type`.
--
-- Миграция аддитивна: существующие таблицы и строки не переписываются. Событие
-- `household_exported` пишет `admin::export` от системного актора, поэтому и
-- выгрузка CLI, и выгрузка из консоли оставляют одну и ту же запись (design,
-- решение 4). Payload события пуст: ни участников, ни списков, ни задач в
-- журнале нет — только household в колонке `household_id`.
--
-- Новое значение enum нельзя использовать в той же транзакции, где оно
-- добавлено: PostgreSQL отвечает ошибкой. Миграция значение не использует —
-- событие `household_exported` пишет код приложения после миграций.

ALTER TYPE audit_event_type ADD VALUE IF NOT EXISTS 'household_exported';
