-- Носитель reply-клавиатуры кнопки «Меню»: колонка `keyboard_message_id` в
-- `telegram_views` хранит id сообщения-носителя в чате (NULL — носителя нет),
-- а значение `keyboard` в `outbox_kind` — вид строки outbox для его доставки
-- (design, решение 2). Telegram допускает в сообщении только один вид
-- `reply_markup`, поэтому клавиатура живёт на отдельном сообщении, а не на
-- экране с inline-кнопками.
--
-- Миграция аддитивна: существующие строки не переписываются, новая колонка
-- nullable и без значения по умолчанию — у существующих чатов носителя нет.
--
-- Новое значение enum нельзя использовать в той же транзакции, где оно
-- добавлено: PostgreSQL отвечает ошибкой. Миграция значение не использует —
-- строки outbox вида `keyboard` начнёт писать код приложения после миграций.

ALTER TABLE telegram_views ADD COLUMN keyboard_message_id bigint;

ALTER TYPE outbox_kind ADD VALUE IF NOT EXISTS 'keyboard';